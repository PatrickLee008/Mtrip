SET NAMES utf8mb4;
USE mtrip_business;

CREATE TABLE IF NOT EXISTS order_checkout_session (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 site_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 checkout_key VARCHAR(64) NOT NULL, items_hash CHAR(64) NOT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 started_at DATETIME NOT NULL, expires_at DATETIME NOT NULL,
 trip_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_checkout (user_id,site_id,checkout_key), KEY idx_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
